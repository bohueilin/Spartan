package com.spartan.data.export

import com.spartan.data.local.DailyReflectionEntity
import com.spartan.data.local.GoalEntity
import com.spartan.data.local.MetricEntryEntity
import com.spartan.data.local.PlanWorkoutOverrideEntity
import com.spartan.data.local.PressureWindowEntity
import com.spartan.data.local.ReminderEntity
import com.spartan.data.local.TargetEntity
import com.spartan.data.local.UserProfileEntity
import com.spartan.data.local.WorkoutSessionEntity
import com.spartan.domain.engine.PlanConstraints
import java.time.LocalDate
import java.util.Locale

object LocalExportFormatter {
    fun format(
        profile: UserProfileEntity?,
        metrics: List<MetricEntryEntity>,
        targets: List<TargetEntity>,
        workouts: List<WorkoutSessionEntity>,
        planOverrides: List<PlanWorkoutOverrideEntity> = emptyList(),
        reminders: List<ReminderEntity>,
        goals: List<GoalEntity> = emptyList(),
        pressureWindows: List<PressureWindowEntity> = emptyList(),
        planConstraints: PlanConstraints = PlanConstraints(),
        /** The user's end-of-day reflections — their own words, so every one of them leaves. */
        reflections: List<DailyReflectionEntity> = emptyList(),
        /** The day of the last weekly goal check-in; null when there has been none. */
        lastGoalReviewDay: Long? = null,
    ): String = buildString {
        appendLine("Spartan Local Export")
        appendLine("Generated by local app export")
        appendLine()

        if (goals.isNotEmpty()) {
            appendLine("[Goals]")
            goals.forEach {
                appendLine(
                    "${it.type} target=${it.targetValue} baseline=${it.baselineValue ?: "-"} " +
                        "days=${it.startEpochDay}..${it.targetEpochDay} status=${it.status}",
                )
            }
            appendLine()
        }
        if (pressureWindows.isNotEmpty()) {
            appendLine("[Pressure windows]")
            pressureWindows.forEach {
                appendLine("mask=${it.daysOfWeekMask} ${it.startMinuteOfDay}-${it.endMinuteOfDay} ${it.label}")
            }
            appendLine()
        }
        // What the user told the goal wizard is their data too: time per day, sleep window,
        // won't-dos and the free-text limits note all leave with the export.
        if (!planConstraints.isEmpty) {
            appendLine("[Plan settings]")
            appendLine(csv("minutesPerDay", "bedtime", "wakeTime", "wontDo", "limitsNote"))
            appendLine(
                csv(
                    planConstraints.minutesPerDay ?: "",
                    planConstraints.bedtimeMinute?.let(::clock).orEmpty(),
                    planConstraints.wakeMinute?.let(::clock).orEmpty(),
                    planConstraints.avoid.sortedBy { it.ordinal }.joinToString(";") { it.name },
                    planConstraints.limitsNote,
                ),
            )
            appendLine()
        }
        if (lastGoalReviewDay != null) {
            appendLine("[Weekly check-in]")
            appendLine(csv("lastReviewDate"))
            appendLine(csv(LocalDate.ofEpochDay(lastGoalReviewDay)))
            appendLine()
        }

        appendLine("[Profile]")
        appendLine(csv("id", "displayName", "heightCm", "birthYear", "sexAtBirth", "updatedAtMillis"))
        if (profile != null) {
            appendLine(csv(profile.id, profile.displayName, profile.heightCm, profile.birthYear, profile.sexAtBirth, profile.updatedAtMillis))
        }
        appendLine()

        appendLine("[Metrics]")
        appendLine(csv("id", "recordedDate", "type", "value", "unit", "note", "createdAtMillis"))
        metrics.forEach {
            appendLine(csv(it.id, LocalDate.ofEpochDay(it.recordedAtEpochDay), it.type.name, it.value ?: "pending", it.unit, it.note, it.createdAtMillis))
        }
        appendLine()

        appendLine("[Targets]")
        appendLine(csv("id", "metricType", "minValue", "maxValue", "note"))
        targets.forEach {
            appendLine(csv(it.id, it.metricType.name, it.minValue ?: "", it.maxValue ?: "", it.note))
        }
        appendLine()

        appendLine("[Workout logs]")
        appendLine(csv("id", "completedDate", "type", "plannedMinutes", "completedMinutes", "rpe", "painFlag"))
        workouts.forEach {
            appendLine(csv(it.id, LocalDate.ofEpochDay(it.completedAtEpochDay), it.type.name, it.plannedMinutes, it.completedMinutes, it.rpe, it.painFlag))
        }
        appendLine()

        // Free-text notes are escaped like every other field, so a comma or line break in the
        // user's own words can never split a row.
        appendLine("[Reflections]")
        appendLine(csv("date", "mood", "note"))
        reflections.sortedBy { it.dateEpochDay }.forEach {
            appendLine(csv(LocalDate.ofEpochDay(it.dateEpochDay), it.mood, it.note))
        }
        appendLine()

        appendLine("[Plan overrides]")
        appendLine(csv("slotKey", "minutes", "updatedAtMillis"))
        planOverrides.forEach {
            appendLine(csv(it.slotKey, it.minutes, it.updatedAtMillis))
        }
        appendLine()

        appendLine("[Reminders]")
        appendLine(csv("id", "title", "body", "hour", "minute", "enabled", "frequency", "daysOfWeekMask", "updatedAtMillis"))
        reminders.forEach {
            appendLine(csv(it.id, it.title, it.body, it.hour, it.minute, it.enabled, it.frequency.name, it.daysOfWeekMask, it.updatedAtMillis))
        }
    }

    /** Minute of day as 24-hour "22:30" — unambiguous in any locale. */
    private fun clock(minuteOfDay: Int): String {
        val m = Math.floorMod(minuteOfDay, 24 * 60)
        return String.format(Locale.ROOT, "%02d:%02d", m / 60, m % 60)
    }

    private fun csv(vararg values: Any?): String = values.joinToString(",") { value ->
        val text = value?.toString().orEmpty()
        if (text.any { it == ',' || it == '"' || it == '\n' || it == '\r' }) {
            "\"" + text.replace("\"", "\"\"") + "\""
        } else {
            text
        }
    }
}
